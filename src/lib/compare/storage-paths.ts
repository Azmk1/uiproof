/**
 * Path-level storage rules for generated artifacts. Kept free of filesystem
 * calls so the traversal guards can be unit tested directly.
 */
import path from "node:path";

export const DEFAULT_DATA_DIRNAME = ".uiproof";

export const ARTIFACT_FILENAMES = {
  baseline: "baseline.png",
  current: "current.png",
  diff: "diff.png",
} as const;

export type ArtifactName = keyof typeof ARTIFACT_FILENAMES;
export const ARTIFACT_NAMES = Object.keys(ARTIFACT_FILENAMES) as readonly ArtifactName[];
export const REPORT_FILENAME = "report.json";

const SAFE_ID = /^[a-z0-9][a-z0-9-]{2,79}$/;
const SAFE_FILENAME = /^[a-z0-9][a-z0-9-]{0,31}\.(png|json)$/;

/** Artifacts live outside `.next` but inside the project so they survive restarts. */
export function resolveDataDir(cwd: string = process.cwd()): string {
  const override = process.env.UIPROOF_DATA_DIR;
  if (override && override.trim().length > 0) return path.resolve(cwd, override.trim());
  return path.join(cwd, DEFAULT_DATA_DIRNAME, "data");
}

export function resolveReportsDir(cwd?: string): string {
  return path.join(resolveDataDir(cwd), "reports");
}

/**
 * Accessibility and responsive audits are stored beside run reports, one directory per
 * audit, holding the structured report and one screenshot per audited viewport. They are
 * kept apart from `.uiproof/data/reports` on purpose: an audit is not a comparison, has no
 * baseline and must never be mistaken for an approval.
 */
export const AUDIT_REPORT_FILENAME = "audit.json";

/** `desktop.png`, `mobile.png`, … — one screenshot per audited viewport preset. */
export const AUDIT_SCREENSHOT_PATTERN = /^[a-z0-9][a-z0-9-]{1,31}\.png$/;

export function resolveAuditsDir(cwd?: string): string {
  return path.join(resolveDataDir(cwd), "audits");
}

/** Audit ids are generated by this project as `audit-<uuid>`, so the same guard applies. */
export function isValidAuditId(id: unknown): id is string {
  return isValidReportId(id);
}

export function resolveAuditDir(auditId: unknown, cwd?: string): string {
  if (!isValidAuditId(auditId)) {
    throw new RangeError(`Invalid audit id: ${String(auditId)}`);
  }
  const auditsDir = resolveAuditsDir(cwd);
  return assertInside(auditsDir, path.join(auditsDir, auditId));
}

/** Absolute path of the structured audit report, guarded against traversal. */
export function resolveAuditReportPath(auditId: unknown, cwd?: string): string {
  return assertInside(resolveAuditDir(auditId, cwd), path.join(resolveAuditDir(auditId, cwd), AUDIT_REPORT_FILENAME));
}

/** Absolute path of one audit screenshot (`<viewportId>.png`), guarded against traversal. */
export function resolveAuditScreenshotPath(auditId: unknown, viewportId: unknown, cwd?: string): string {
  if (typeof viewportId !== "string" || !AUDIT_SCREENSHOT_PATTERN.test(`${viewportId}.png`)) {
    throw new RangeError(`Invalid audit viewport id: ${String(viewportId)}`);
  }
  const directory = resolveAuditDir(auditId, cwd);
  return assertInside(directory, path.join(directory, `${viewportId}.png`));
}

/**
 * Diagnoses are stored beside audits, one directory per diagnosis, holding one JSON file.
 * They are kept apart from `reports/` and `audits/` for the same reason those are kept
 * apart from each other: a diagnosis is a model's interpretation, and nothing that decides
 * a pass or a fail may ever be read from here.
 */
export const DIAGNOSIS_FILENAME = "diagnosis.json";

export function resolveDiagnosesDir(cwd?: string): string {
  return path.join(resolveDataDir(cwd), "diagnoses");
}

/** Diagnosis ids are generated by this project as `diag-<uuid>`. */
export function isValidDiagnosisId(id: unknown): id is string {
  return isValidReportId(id);
}

export function resolveDiagnosisDir(diagnosisId: unknown, cwd?: string): string {
  if (!isValidDiagnosisId(diagnosisId)) {
    throw new RangeError(`Invalid diagnosis id: ${String(diagnosisId)}`);
  }
  const diagnosesDir = resolveDiagnosesDir(cwd);
  return assertInside(diagnosesDir, path.join(diagnosesDir, diagnosisId));
}

/** Absolute path of a stored diagnosis, guarded against traversal. */
export function resolveDiagnosisReportPath(diagnosisId: unknown, cwd?: string): string {
  const directory = resolveDiagnosisDir(diagnosisId, cwd);
  return assertInside(directory, path.join(directory, DIAGNOSIS_FILENAME));
}

/** True when a requested audit file is one the store is allowed to serve. */
export function isAuditFileName(name: unknown): name is string {
  if (typeof name !== "string") return false;
  if (name === AUDIT_REPORT_FILENAME) return true;
  return AUDIT_SCREENSHOT_PATTERN.test(name) && !name.includes("..") && !name.includes("/");
}

/**
 * Repairs are stored beside diagnoses, one directory per run, holding the record, one
 * patch file per attempt and the before/after screenshots the sandbox produced. They are
 * kept apart from `reports/`, `audits/` and `diagnoses/` because a repair attempt is an
 * experiment in an isolated checkout — never a measurement of the developer's tree.
 */
export const REPAIR_FILENAME = "repair.json";
export const REPAIR_PATCH_PATTERN = /^attempt-[12]\.patch$/;
/**
 * The model answer exactly as it arrived, kept for an attempt whose answer was unusable.
 * A rejected patch is the most convincing evidence this feature produces, and a rejected
 * *answer* — malformed JSON, a missing field, an invented issue key — is evidence too.
 */
export const REPAIR_REPLY_PATTERN = /^attempt-[12]-reply\.txt$/;
export const REPAIR_ARTIFACT_PATTERN = /^[a-z0-9][a-z0-9-]{0,72}\.png$/;

/** Text artifacts (a patch or a raw reply) are served as text, images as PNG. */
export function repairArtifactContentType(name: string): string {
  return name.endsWith(".png") ? "image/png" : "text/plain; charset=utf-8";
}

export function resolveRepairsDir(cwd?: string): string {
  return path.join(resolveDataDir(cwd), "repairs");
}

/** Repair ids are generated by this project as `repair-<uuid>`. */
export function isValidRepairId(id: unknown): id is string {
  return isValidReportId(id);
}

export function resolveRepairDir(repairId: unknown, cwd?: string): string {
  if (!isValidRepairId(repairId)) {
    throw new RangeError(`Invalid repair id: ${String(repairId)}`);
  }
  const repairsDir = resolveRepairsDir(cwd);
  return assertInside(repairsDir, path.join(repairsDir, repairId));
}

/** Absolute path of the stored repair record, guarded against traversal. */
export function resolveRepairRecordPath(repairId: unknown, cwd?: string): string {
  const directory = resolveRepairDir(repairId, cwd);
  return assertInside(directory, path.join(directory, REPAIR_FILENAME));
}

export function isRepairArtifactName(name: unknown): name is string {
  return (
    typeof name === "string" &&
    (REPAIR_ARTIFACT_PATTERN.test(name) || REPAIR_PATCH_PATTERN.test(name) || REPAIR_REPLY_PATTERN.test(name)) &&
    !name.includes("..") &&
    !name.includes("/")
  );
}

/** Absolute path of one repair artifact (a PNG or an attempt patch). */
export function resolveRepairArtifactPath(repairId: unknown, name: unknown, cwd?: string): string {
  if (!isRepairArtifactName(name)) {
    throw new RangeError(`Invalid repair artifact name: ${String(name)}`);
  }
  const directory = resolveRepairDir(repairId, cwd);
  return assertInside(directory, path.join(directory, name));
}

export function isValidReportId(id: unknown): id is string {
  return typeof id === "string" && SAFE_ID.test(id) && !id.includes("..") && !id.includes("/");
}

export function isValidFileName(name: unknown): name is string {
  return typeof name === "string" && SAFE_FILENAME.test(name) && !name.includes("..") && !name.includes("/");
}

export function isArtifactName(value: unknown): value is ArtifactName {
  return typeof value === "string" && (ARTIFACT_NAMES as readonly string[]).includes(value);
}

function assertInside(parent: string, candidate: string): string {
  const resolvedParent = path.resolve(parent);
  const resolved = path.resolve(candidate);
  if (resolved !== resolvedParent && !resolved.startsWith(resolvedParent + path.sep)) {
    throw new RangeError(`Refusing to access a path outside the data directory: ${candidate}`);
  }
  return resolved;
}

/** Absolute path of one run directory. Throws for unsafe ids. */
export function resolveReportDir(reportId: unknown, cwd?: string): string {
  if (!isValidReportId(reportId)) {
    throw new RangeError(`Invalid report id: ${String(reportId)}`);
  }
  const reportsDir = resolveReportsDir(cwd);
  return assertInside(reportsDir, path.join(reportsDir, reportId));
}

/** Absolute path of a stored artifact, guarded against traversal. */
export function resolveArtifactPath(reportId: unknown, fileName: unknown, cwd?: string): string {
  if (!isValidFileName(fileName)) {
    throw new RangeError(`Invalid artifact file name: ${String(fileName)}`);
  }
  const reportDir = resolveReportDir(reportId, cwd);
  return assertInside(reportDir, path.join(reportDir, fileName));
}
